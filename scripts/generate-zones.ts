// Writes src/zones.ts from the names of a time zone database, one per line on standard input:
//   unzip -Z1 "$(go env GOROOT)/lib/time/zoneinfo.zip" | node scripts/generate-zones.ts <tzdb release>
import { readFileSync, writeFileSync } from "node:fs";

const release = process.argv[2];
if (!release) throw new Error("usage: generate-zones.ts <tzdb release>");
const names = readFileSync(0, "utf8").split("\n").filter((n) => /^[A-Z][A-Za-z0-9_+-]*(\/[A-Z][A-Za-z0-9_+-]*)+$/.test(n)).sort();
const lines = names.map((n) => `  ${JSON.stringify(n)},`).join("\n");
writeFileSync(
  new URL("../src/zones.ts", import.meta.url),
  `// SPDX-License-Identifier: Apache-2.0\n\n// Generated by scripts/generate-zones.ts from the IANA time zone database ${release}, including\n// links. Intl matches names without regard to case and has no list of links, so the\n// exact spelling (SPEC-v0 section 4.2) is compared against this list.\n\nexport const ZONE_NAMES: ReadonlySet<string> = new Set([\n${lines}\n]);\n`,
);
